-- Explicit grants are required on projects that do not auto-expose SQL tables.
revoke all on table
  public.championship_cup,
  public.championship_cup_round,
  public.championship_cup_entry
from anon, authenticated;
grant select on table
  public.championship_cup,
  public.championship_cup_round,
  public.championship_cup_entry
to anon;
grant select, insert, update, delete on table
  public.championship_cup,
  public.championship_cup_round
to authenticated;
grant select, insert, delete on table
  public.championship_cup_entry
to authenticated;
grant all privileges on table
  public.championship_cup,
  public.championship_cup_round,
  public.championship_cup_entry
to service_role;
grant usage, select on sequence public.championship_cup_id_seq
  to authenticated, service_role;

create policy "Published cups are readable to visitors"
  on public.championship_cup for select
  to anon
  using (published_at is not null and is_enabled);
create policy "Published cups or admins are readable"
  on public.championship_cup for select
  to authenticated
  using (
    (published_at is not null and is_enabled)
    or exists (
      select 1 from public.app_admins where user_id = (select auth.uid())
    )
  );
create policy "Published cups or admins can read rounds"
  on public.championship_cup_round for select
  to anon, authenticated
  using (
    exists (select 1 from public.championship_cup where id = cup_id)
  );
create policy "Published cups or admins can read entries"
  on public.championship_cup_entry for select
  to anon, authenticated
  using (
    exists (select 1 from public.championship_cup where id = cup_id)
  );

create policy "Admins can insert cups"
  on public.championship_cup for insert to authenticated
  with check (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));
create policy "Admins can update cups"
  on public.championship_cup for update to authenticated
  using (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));
create policy "Admins can delete cups"
  on public.championship_cup for delete to authenticated
  using (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));

create policy "Admins can insert cup rounds"
  on public.championship_cup_round for insert to authenticated
  with check (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));
create policy "Admins can update cup rounds"
  on public.championship_cup_round for update to authenticated
  using (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));
create policy "Admins can delete cup rounds"
  on public.championship_cup_round for delete to authenticated
  using (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));

create policy "Admins can insert cup entries"
  on public.championship_cup_entry for insert to authenticated
  with check (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));
create policy "Admins can delete cup entries"
  on public.championship_cup_entry for delete to authenticated
  using (exists (
    select 1 from public.app_admins where user_id = (select auth.uid())
  ));

revoke all on function
  public.validate_championship_cup_round(),
  public.validate_championship_cup_entry(),
  public.protect_started_cup_entry_identity(),
  public.validate_championship_cup_publication()
from public, anon, authenticated;
