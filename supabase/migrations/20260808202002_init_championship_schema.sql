-- Pisa Fundo championship schema
--
-- This migration is intentionally safe to apply to the database originally
-- created by Django: existing tables and rows are preserved. On a fresh
-- Supabase project it creates the same public schema expected by the Next.js
-- application.

begin;

create table if not exists public.championship_season (
  id bigint generated by default as identity,
  name varchar(100) not null,
  year integer not null,
  is_active boolean not null default false,
  constraint championship_season_pkey primary key (id),
  constraint championship_season_year_check check (year >= 0)
);

create table if not exists public.championship_team (
  id bigint generated by default as identity,
  name varchar(100) not null,
  slug varchar(120) not null,
  primary_color varchar(7) not null,
  secondary_color varchar(7) not null,
  constraint championship_team_pkey primary key (id),
  constraint championship_team_name_key unique (name),
  constraint championship_team_slug_key unique (slug)
);

create table if not exists public.championship_driver (
  id bigint generated by default as identity,
  name varchar(100) not null,
  nickname varchar(50) not null default '',
  slug varchar(120) not null,
  number integer,
  constraint championship_driver_pkey primary key (id),
  constraint championship_driver_slug_key unique (slug),
  constraint championship_driver_number_check check (number >= 0)
);

create table if not exists public.championship_driverteamseason (
  id bigint generated by default as identity,
  car_number integer,
  driver_id bigint not null,
  season_id bigint not null,
  team_id bigint not null,
  is_guest boolean not null default false,
  constraint championship_driverteamseason_pkey primary key (id),
  constraint championship_driverteamseason_car_number_check check (car_number >= 0),
  constraint championship_driverteamseason_season_driver_key unique (season_id, driver_id),
  constraint championship_driverteamseason_driver_fkey
    foreign key (driver_id) references public.championship_driver(id)
    deferrable initially deferred,
  constraint championship_driverteamseason_season_fkey
    foreign key (season_id) references public.championship_season(id)
    deferrable initially deferred,
  constraint championship_driverteamseason_team_fkey
    foreign key (team_id) references public.championship_team(id)
    deferrable initially deferred
);

create table if not exists public.championship_round (
  id bigint generated by default as identity,
  name varchar(100) not null,
  date date not null,
  location varchar(100) not null,
  "order" integer not null,
  season_id bigint not null,
  constraint championship_round_pkey primary key (id),
  constraint championship_round_order_check check ("order" >= 0),
  constraint championship_round_season_order_key unique (season_id, "order"),
  constraint championship_round_season_fkey
    foreign key (season_id) references public.championship_season(id)
    deferrable initially deferred
);

create table if not exists public.championship_roundresult (
  id bigint generated by default as identity,
  position integer not null,
  fastest_lap boolean not null default false,
  points integer not null default 0,
  entry_id bigint not null,
  round_id bigint not null,
  has_penalty boolean not null default false,
  penalty_reason varchar(200) not null default '',
  status varchar(10) not null default 'COMPLETED',
  constraint championship_roundresult_pkey primary key (id),
  constraint championship_roundresult_position_check check (position >= 0),
  constraint championship_roundresult_points_check check (points >= 0),
  constraint championship_roundresult_entry_fkey
    foreign key (entry_id) references public.championship_driverteamseason(id)
    deferrable initially deferred,
  constraint championship_roundresult_round_fkey
    foreign key (round_id) references public.championship_round(id)
    deferrable initially deferred
);

-- Defaults are added to the legacy Django tables as well. These changes do
-- not rewrite existing rows and make manual entry in Supabase less error-prone.
alter table public.championship_season
  alter column is_active set default false;
alter table public.championship_driver
  alter column nickname set default '';
alter table public.championship_driverteamseason
  alter column is_guest set default false;
alter table public.championship_roundresult
  alter column fastest_lap set default false,
  alter column points set default 0,
  alter column has_penalty set default false,
  alter column penalty_reason set default '',
  alter column status set default 'COMPLETED';

-- Constraints that were previously enforced only by Django model validation.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'championship_roundresult_status_check'
      and conrelid = 'public.championship_roundresult'::regclass
  ) then
    alter table public.championship_roundresult
      add constraint championship_roundresult_status_check
      check (status in ('COMPLETED', 'DNF', 'DNS'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'championship_roundresult_position_positive_check'
      and conrelid = 'public.championship_roundresult'::regclass
  ) then
    alter table public.championship_roundresult
      add constraint championship_roundresult_position_positive_check
      check (position >= 1);
  end if;
end;
$$;

create unique index if not exists championship_roundresult_round_entry_uniq
  on public.championship_roundresult (round_id, entry_id);

create unique index if not exists championship_roundresult_round_position_uniq
  on public.championship_roundresult (round_id, position)
  where status <> 'DNS';

create unique index if not exists championship_roundresult_fastest_lap_uniq
  on public.championship_roundresult (round_id)
  where fastest_lap;

