-- Django's auth/session tables are not part of the public website API. Lock
-- them down if they exist in a database migrated from the legacy application.
do $$
declare
  internal_table record;
begin
  for internal_table in
    select schemaname, tablename
    from pg_tables
    where schemaname = 'public'
      and tablename ~ '^(auth|django)_'
  loop
    execute format('revoke all on table %I.%I from anon, authenticated', internal_table.schemaname, internal_table.tablename);
    execute format('alter table %I.%I enable row level security', internal_table.schemaname, internal_table.tablename);
  end loop;
end;
$$;

