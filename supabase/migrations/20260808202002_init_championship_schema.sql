-- Keep the stored points in sync with lib/scoring.ts, including entries made
-- directly through the Supabase Table Editor.
create or replace function public.set_roundresult_points()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  season_year integer;
  base_points integer := 0;
begin
  if new.status in ('DNF', 'DNS') then
    new.points := 0;
    return new;
  end if;

  select season.year
    into season_year
  from public.championship_round as round
  join public.championship_season as season on season.id = round.season_id
  where round.id = new.round_id;

  if season_year is null then
    raise exception 'Etapa % nao pertence a uma temporada valida.', new.round_id;
  end if;

  if season_year = 2025 then
    base_points := case new.position
      when 1 then 25 when 2 then 18 when 3 then 15 when 4 then 12
      when 5 then 10 when 6 then 8 when 7 then 6 when 8 then 4
      when 9 then 2 when 10 then 1 else 0
    end;
  else
    base_points := case new.position
      when 1 then 18 when 2 then 15 when 3 then 13 when 4 then 11
      when 5 then 9 when 6 then 7 when 7 then 5 when 8 then 3
      when 9 then 2 when 10 then 1 else 0
    end;
  end if;

  new.points := base_points + case when new.fastest_lap then 1 else 0 end;
  return new;
end;
$$;

drop trigger if exists set_roundresult_points_before_write
  on public.championship_roundresult;
create trigger set_roundresult_points_before_write
before insert or update of position, fastest_lap, status, round_id
on public.championship_roundresult
for each row execute function public.set_roundresult_points();

-- Preserve the original rule: at most two drivers per team in each season.
create or replace function public.enforce_team_driver_limit()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  current_driver_count integer;
begin
  select count(*)::integer
    into current_driver_count
  from public.championship_driverteamseason
  where season_id = new.season_id
    and team_id = new.team_id
    and id <> coalesce(new.id, 0);

  if current_driver_count >= 2 then
    raise exception 'Esta equipe ja tem 2 pilotos nesta temporada.';
  end if;

  return new;
end;
$$;

drop trigger if exists enforce_team_driver_limit_before_write
  on public.championship_driverteamseason;
create trigger enforce_team_driver_limit_before_write
before insert or update of season_id, team_id
on public.championship_driverteamseason
for each row execute function public.enforce_team_driver_limit();

